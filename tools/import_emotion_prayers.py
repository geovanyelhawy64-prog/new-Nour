def main():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    c.execute('''CREATE TABLE IF NOT EXISTS emotion_prayers (
        id INTEGER PRIMARY KEY,
        category TEXT NOT NULL,
        title TEXT NOT NULL,
        verse_text TEXT NOT NULL,
        verse_reference TEXT NOT NULL,
        psalm_text TEXT,
        psalm_reference TEXT,
        agpeya_prayer TEXT,
        agpeya_reference TEXT,
        meditation TEXT NOT NULL,
        sort_order INTEGER NOT NULL
    )''')

    c.execute('DELETE FROM emotion_prayers')
    c.executemany(
        'INSERT INTO emotion_prayers (id, category, title, verse_text, verse_reference, psalm_text, psalm_reference, agpeya_prayer, agpeya_reference, meditation, sort_order) VALUES (?,?,?,?,?,?,?,?,?,?,?)',
        DATA
    )

    conn.commit()
    print(f'Successfully imported {len(DATA)} emotion prayers into noor.db')
    conn.close()

if __name__ == '__main__':
    main()
