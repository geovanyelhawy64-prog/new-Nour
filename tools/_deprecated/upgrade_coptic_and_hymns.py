def generate_syllables(phonetic_text, coptic_text):
    pho_words = phonetic_text.replace(':', '').replace('.', '').split()
    cop_words = coptic_text.replace(':', '').replace('.', '').split()
    
    syllables = []
    pitches = ['medium', 'ascending', 'high', 'descending', 'low']
    
    for idx, p_w in enumerate(pho_words):
        c_w = cop_words[idx] if idx < len(cop_words) else ''
        syllables.append({
            's': p_w,
            'c': c_w,
            'v': (idx % 3) + 1,
            'p': pitches[idx % len(pitches)],
            'ms': 600 + ((idx % 4) * 250)
        })
    return json.dumps(syllables, ensure_ascii=False)

