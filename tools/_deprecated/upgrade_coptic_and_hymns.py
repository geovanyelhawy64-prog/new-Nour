def convert_coptic(text):
    if not text:
        return text
    text = text.replace('“', '"').replace('”', '"').replace('‘', "'").replace('’', "'")
    out = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == '`':
            if i + 1 < n:
                next_raw = text[i+1]
                next_copt = ATHANASIUS_MAP.get(next_raw, next_raw)
                out.append(next_copt + '\u0300')
                i += 2
            else:
                out.append('\u0300')
                i += 1
        elif ch in ATHANASIUS_MAP:
            out.append(ATHANASIUS_MAP[ch])
            i += 1
        else:
            out.append(ch)
            i += 1
            
    res = "".join(out)
    res = re.sub(r'Ⲡⲉⲛ\s*̅', 'Ⲡⲉⲛϭⲟⲓⲥ', res)
    res = re.sub(r'Ⲡⲉⲛ_', 'Ⲡⲉⲛϭⲟⲓⲥ', res)
    return res

