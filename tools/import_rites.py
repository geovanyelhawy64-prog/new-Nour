def main():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    c.execute('''CREATE TABLE IF NOT EXISTS rites (
        id INTEGER PRIMARY KEY,
        name_ar TEXT NOT NULL,
        name_en TEXT,
        name_coptic TEXT,
        category TEXT NOT NULL,
        description TEXT,
        sort_order INTEGER NOT NULL,
        icon TEXT
    )''')

    c.execute('''CREATE TABLE IF NOT EXISTS rite_sections (
        id INTEGER PRIMARY KEY,
        rite_id INTEGER NOT NULL,
        title_ar TEXT NOT NULL,
        text_ar TEXT NOT NULL,
        coptic_text TEXT,
        coptic_arabic_text TEXT,
        rubric TEXT,
        response TEXT,
        sort_order INTEGER NOT NULL,
        FOREIGN KEY (rite_id) REFERENCES rites(id)
    )''')

    c.execute('DELETE FROM rite_sections')
    c.execute('DELETE FROM rites')

    c.executemany(
        'INSERT INTO rites VALUES (?,?,?,?,?,?,?,?)', RITES)
    c.executemany(
        'INSERT INTO rite_sections VALUES (?,?,?,?,?,?,?,?,?)', SECTIONS)

    conn.commit()
    print(f'Imported {len(RITES)} rites, {len(SECTIONS)} sections')
    conn.close()

if __name__ == '__main__':
    main()
