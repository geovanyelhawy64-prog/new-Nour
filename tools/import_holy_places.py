def main():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    c.execute('''CREATE TABLE IF NOT EXISTS holy_places (
        id INTEGER PRIMARY KEY,
        name_ar TEXT NOT NULL,
        name_coptic TEXT,
        type TEXT NOT NULL,
        governorate TEXT NOT NULL,
        location_description TEXT NOT NULL,
        latitude REAL,
        longitude REAL,
        century TEXT,
        patron_saint TEXT,
        history TEXT NOT NULL,
        feast_day TEXT,
        visiting_rules TEXT,
        sort_order INTEGER NOT NULL
    )''')

    c.execute('DELETE FROM holy_places')

    c.executemany(
        'INSERT INTO holy_places (id, name_ar, name_coptic, type, governorate, location_description, latitude, longitude, century, patron_saint, history, feast_day, visiting_rules, sort_order) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
        PLACES
    )

    conn.commit()
    print(f'Successfully imported {len(PLACES)} holy places and monasteries into noor.db')
    conn.close()

if __name__ == '__main__':
    main()
