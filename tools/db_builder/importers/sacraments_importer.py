def import_sacraments(cursor: sqlite3.Cursor):
    print("Populating Seven Holy Sacraments with canonical teachings and scriptures...")
    # 1. Update/Ensure Sacraments Master List
    cursor.execute("DELETE FROM sacrament_sections;")
    cursor.execute("DELETE FROM sacraments;")

    cursor.executemany("""
        INSERT INTO sacraments (id, name_ar, sacrament_order)
        VALUES (?, ?, ?)
    """, SACRAMENTS_DATA)

    # 2. Insert Complete Liturgical Sections
    cursor.executemany("""
        INSERT INTO sacrament_sections (sacrament_id, title, content, scriptures, section_order)
        VALUES (?, ?, ?, ?, ?)
    """, SACRAMENT_SECTIONS_DATA)

    print(f"Successfully inserted {len(SACRAMENTS_DATA)} sacraments and {len(SACRAMENT_SECTIONS_DATA)} canonical sections.")
