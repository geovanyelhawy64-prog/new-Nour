/// كائن يمثل الشاهد الكتابي المحلول
class ResolvedScriptureRef {
  final int bookId;
  final String bookName;
  final int chapter;
  final int? verse;
  final String displayText;

  const ResolvedScriptureRef({
    required this.bookId,
    required this.bookName,
    required this.chapter,
    this.verse,
    required this.displayText,
  });

  String get routePath => '/bible/read/$bookId/$chapter';
}

