  /// محاولة استخلاص شاهد كتابي من نص الإدخال
  /// يُرجع `null` إذا لم يكن النص يمثل شاهداً كتابياً
  static ResolvedScriptureRef? resolve(String input) {
    if (input.trim().isEmpty) return null;

    // تطبيع الأرقام من العربية للإنجليزية
    String s = input.trim();
    const arabicNums = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    for (int i = 0; i < 10; i++) {
      s = s.replaceAll(arabicNums[i], i.toString());
    }

    // استخراج الشاهد بالريجكس: اسم السفر + الإصحاح + اختياري نقطتين والآية
    // مثل: "يو 3:16", "مز 51", "مت 5", "رو 8 : 28"
    final regex = RegExp(
      r'^([0-9]?\s*[\u0600-\u06FF\s]+?)\s*(\d+)(?:\s*[:,\.]\s*(\d+))?$',
    );
    final match = regex.firstMatch(s);
    if (match == null) return null;

    final rawBook = match.group(1)?.trim();
    final chapStr = match.group(2);
    final verseStr = match.group(3);

    if (rawBook == null || chapStr == null) return null;

    final normBook = SearchNormalizer.normalize(rawBook);
    int? bookId = _bookAbbreviations[rawBook] ?? _bookAbbreviations[normBook];

    // محاولة ثانية بالتطبيع الخفيف
    if (bookId == null) {
      for (final entry in _bookAbbreviations.entries) {
        if (SearchNormalizer.normalize(entry.key) == normBook) {
          bookId = entry.value;
          break;
        }
      }
    }

    if (bookId == null) return null;

    final chapter = int.tryParse(chapStr);
    if (chapter == null || chapter <= 0) return null;

    final verse = verseStr != null ? int.tryParse(verseStr) : null;
    final bookName = _bookDisplayNames[bookId] ?? rawBook;

    final display = verse != null
        ? '$bookName - الإصحاح $chapter : الآية $verse'
        : '$bookName - الإصحاح $chapter';

    return ResolvedScriptureRef(
      bookId: bookId,
      bookName: bookName,
      chapter: chapter,
      verse: verse,
      displayText: display,
    );
  }
